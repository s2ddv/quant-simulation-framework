def test_calibrate_on_synthetic_series(calibrated: GarchTSimulator) -> None:
    fit = calibrated.fit_result
    assert fit is not None and fit["converged"] is True and fit["n_obs"] == 2000
    assert calibrated.h0_source == "calibrated_h_next" and calibrated.h0 > 0
    assert calibrated.alpha is not None and calibrated.beta is not None
    assert calibrated.nu is not None
    # Loose recovery bounds (asymptotic SE of alpha, beta ~ 0.02-0.04 at
    # n = 2000); this is a wiring check, not an estimator study.
    assert abs(calibrated.alpha - PARAMS["alpha"]) < 0.1
    assert abs(calibrated.beta - PARAMS["beta"]) < 0.15
    assert 0.5 < calibrated.unconditional_variance() / S2 < 2.0
    assert calibrated.nu > 4
    paths = calibrated.generate_paths()
    assert paths.shape == (31, 500) and np.isfinite(paths).all()


