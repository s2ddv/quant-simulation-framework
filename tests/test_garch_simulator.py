# 1. Equality with backtest.garch.simulate_cumulative
# --------------------------------------------------------------------------
@pytest.mark.parametrize("config", ["unconditional", "user_h0", "calibrated"])
def test_matches_simulate_cumulative(config: str, calibrated: GarchTSimulator) -> None:
    seed = 2024
    if config == "unconditional":
        sim = _sim(40, 3000, seed)
    elif config == "user_h0":
        sim = _sim(25, 2000, seed, h0=9 * S2)
    else:
        sim = GarchTSimulator.from_days(S0, 30, 2500, seed, mu=calibrated.mu,
                                        omega=calibrated.omega, alpha=calibrated.alpha,
                                        beta=calibrated.beta, nu=calibrated.nu,
                                        h0=calibrated.h0)
        assert sim.h0 == calibrated.h0
        assert abs(sim.h0 / sim.unconditional_variance() - 1) > 1e-3  # h0 != s2
    ref = simulate_cumulative(_bt_params(sim), sim.h0, sim.steps, sim.n_sims,
                              np.random.default_rng(seed))
    # Exact: the internal cumulative log returns use the same arithmetic.
    cum, _ = GarchTSimulator.from_days(S0, sim.steps, sim.n_sims, seed, mu=sim.mu,
                                       omega=sim.omega, alpha=sim.alpha, beta=sim.beta,
                                       nu=sim.nu, h0=sim.h0)._simulate_log()
    np.testing.assert_array_equal(cum[-1], ref)
    # Prices are s0*exp(cum): exp/log/division round each by ~1 ulp; |cum| < 1
    # here, so an absolute 1e-12 (~4500 ulp at 1) is a safe bound.
    paths = sim.generate_paths()
    assert np.max(np.abs(ref)) < 1.0
    np.testing.assert_allclose(np.log(paths[-1] / S0), ref, rtol=0, atol=1e-12)


