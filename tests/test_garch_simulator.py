def test_moment_condition() -> None:
    a, b, nu = PARAMS["alpha"], PARAMS["beta"], PARAMS["nu"]
    kappa = 3 * (nu - 2) / (nu - 4)
    assert nu > 4 and b * b + 2 * a * b + a * a * kappa < 1


def _check_long_horizon(sim: GarchTSimulator) -> dict[str, float]:
    """E[e^2] and E[h] on the last simulated day versus s2, at 4 SE."""
    paths, hvar = sim.generate_paths_and_variance()
    e_last = np.log(paths[-1] / paths[-2]) - MU   # shock of day `steps`
    est_e, se_e = _mean_and_se(e_last * e_last)
    est_h, se_h = _mean_and_se(hvar[-2])          # h of day `steps`
    assert abs(est_e - S2) <= K_SE * se_e, (est_e, S2, se_e)
    assert abs(est_h - S2) <= K_SE * se_h, (est_h, S2, se_h)
    return {"est_e2": est_e, "se_e2": se_e, "z_e2": (est_e - S2) / se_e,
            "est_h": est_h, "se_h": se_h, "z_h": (est_h - S2) / se_h}


@pytest.mark.parametrize(("h0", "seed"), [(None, 101), (4 * S2, 102)])
def test_unconditional_variance_long_horizon(h0: float | None, seed: int) -> None:
    # 1000 days: from h0 = 4 s2 the transient of E[h] is 0.95^999 * 3 s2
    # ~ 1e-22 s2, far below the SE (~2e-2 s2 for e^2, ~3e-3 s2 for h with
    # N = 12000). Distinct seeds: with a shared seed the two paths coincide
    # to float precision by day 1000 (the filter forgets h0).
    sim = _sim(1000, 12000, seed, h0=h0)
    assert sim.unconditional_variance() == pytest.approx(S2, rel=1e-15)
    _check_long_horizon(sim)


def test_variance_forecast_from_nonstationary_h0() -> None:
    h0 = 6 * S2
    persistence = PARAMS["alpha"] + PARAMS["beta"]
    sim = _sim(60, 20000, 303, h0=h0)
    paths, hvar = sim.generate_paths_and_variance()
    logp = np.log(paths)
    for k in (1, 5, 20, 59):
        theory = S2 + persistence ** k * (h0 - S2)  # E[h_{1+k}] = E[e_{1+k}^2]
        est_h, se_h = _mean_and_se(hvar[k])
        assert abs(est_h - theory) <= K_SE * se_h, (k, est_h, theory, se_h)
        e = logp[k + 1] - logp[k] - MU             # shock of day k + 1
        est_e, se_e = _mean_and_se(e * e)
        assert abs(est_e - theory) <= K_SE * se_e, (k, est_e, theory, se_e)


@pytest.mark.slow
def test_unconditional_variance_long_horizon_slow() -> None:
    """Five independent batches (seeds 501..505), N = 150000, day 400."""
    e2: list[np.ndarray] = []
    hs: list[np.ndarray] = []
    for seed in range(501, 506):
        sim = _sim(400, 30000, seed)
        paths, hvar = sim.generate_paths_and_variance()
        e = np.log(paths[-1] / paths[-2]) - MU
        e2.append(e * e)
        hs.append(hvar[-2].copy())
        del paths, hvar
    for x in (np.concatenate(e2), np.concatenate(hs)):
        est, se = _mean_and_se(x)
        assert abs(est - S2) <= K_SE * se, (est, S2, se)


@pytest.mark.slow
def test_variance_forecast_slow() -> None:
    h0 = 6 * S2
    persistence = PARAMS["alpha"] + PARAMS["beta"]
    rows: dict[int, list[np.ndarray]] = {k: [] for k in (1, 5, 20, 59)}
    for seed in range(601, 611):  # 10 x 25000 paths, 8*2*61*25000 B ~ 24 MB each
        _, hvar = _sim(60, 25000, seed, h0=h0).generate_paths_and_variance()
        for k in rows:
            rows[k].append(hvar[k].copy())
    for k, parts in rows.items():
        theory = S2 + persistence ** k * (h0 - S2)
        est, se = _mean_and_se(np.concatenate(parts))
        assert abs(est - theory) <= K_SE * se, (k, est, theory, se)


