def test_same_seed_bitwise_and_different_seeds_differ() -> None:
    a = _sim(50, 300, 42).generate_paths()
    b = _sim(50, 300, 42).generate_paths()
    np.testing.assert_array_equal(a, b)
    c = _sim(50, 300, 43).generate_paths()
    assert not np.array_equal(a[1:], c[1:])
    # Repeated calls advance the instance generator.
    sim = _sim(50, 300, 42)
    first, second = sim.generate_paths(), sim.generate_paths()
    np.testing.assert_array_equal(first, a)
    assert not np.array_equal(first[1:], second[1:])


