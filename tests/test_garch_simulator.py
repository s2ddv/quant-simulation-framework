"""Tests for the GARCH(1,1)-t path simulator ``simulation.garch`` (plan E5.3).

Model (one step = one trading day, decimal units)::

    r_t = mu + a_t + e_t,   e_t = sqrt(h_t) z_t,   z_t unit-variance Student-t(nu)
    h_{t+1} = omega + alpha e_t^2 + beta h_t,      h_1 = h0

``mu`` is the daily log-return location (not an annual price drift); ``omega``
and ``h`` are daily variances. ``a_t`` is the ``_drift_adjustment`` hook (0).

Independent references used here (written from the model, not from the code):

* ``backtest.garch.simulate_cumulative``: the published sampler whose draw
  order the simulator must reproduce (same ``default_rng(seed)`` stream).
* Variance forecast of GARCH(1,1) (Bollerslev 1986): with ``s2 = omega / (1 -
  alpha - beta)`` and ``E[e_t^2 | h_t] = h_t``,
  ``E[h_{1+k}] = s2 + (alpha + beta)^k (h0 - s2)``. Starting at ``h0 = s2``
  every day has ``E[h_t] = E[e_t^2] = s2`` exactly; from ``h0 != s2`` the
  transient vanishes geometrically.
* The recursion ``h_{t+1} = omega + alpha e_t^2 + beta h_t`` re-applied to the
  shocks recovered from the returned prices.

Statistical tolerances (plan section 2.5): fixed seeds, ``|estimate - theory|
<= 4 SE`` (false alarm ~6e-5 per assertion under asymptotic normality). Each
mean is over independent paths at one fixed day, so the SE is the sample
standard deviation over ``sqrt(N)``. That SE needs ``Var(e_t^2) < inf``, i.e.
a finite fourth moment of ``e_t``: ``nu > 4`` and the GARCH-t fourth-moment
condition ``beta^2 + 2 alpha beta + alpha^2 kappa_z < 1`` with
``kappa_z = E[z^4] = 3 (nu - 2) / (nu - 4)``. With ``alpha = 0.05``,
``beta = 0.90``, ``nu = 8``: ``kappa_z = 4.5`` and the left side is
``0.81 + 0.09 + 0.01125 = 0.91125 < 1`` (asserted in ``test_moment_condition``).

Memory (``MAX_WORKING_BYTES`` = 256 MiB): the largest fast matrix pair is
``2 * 8 * 1001 * 12000`` B ~ 192 MB (paths + variance); the slow test uses
batches of ``2 * 8 * 401 * 30000`` B ~ 192 MB, released between batches.
Tests marked ``slow`` repeat the long-horizon checks with ~12x more paths
(they run by default; deselect with ``-m "not slow"``).
"""

from __future__ import annotations

import json
import math
import warnings
from typing import Any

import numpy as np
import pandas as pd
import pytest

import simulation.garch as garch_module
from backtest.garch import simulate_cumulative
from simulation.garch import GarchTSimulator

S0 = 100.0
MU = 2e-4
PARAMS: dict[str, Any] = dict(omega=2e-6, alpha=0.05, beta=0.90, nu=8.0)
S2 = PARAMS["omega"] / (1 - PARAMS["alpha"] - PARAMS["beta"])  # 4e-5 per day
K_SE = 4.0


def _sim(days: int, n: int, seed: int | None = 11, **kw: Any) -> GarchTSimulator:
    params: dict[str, Any] = dict(mu=MU, **PARAMS)
    params.update(kw)
    return GarchTSimulator.from_days(S0, days, n, seed, **params)


def _bt_params(sim: GarchTSimulator) -> dict[str, float | None]:
    return {"mu": sim.mu, "omega": sim.omega, "alpha": sim.alpha,
            "beta": sim.beta, "nu": sim.nu}


def _synthetic_prices(days: int = 2000, seed: int = 7) -> pd.Series:
    """Prices generated by the model itself (no network), business-day index."""
    path = _sim(days, 1, seed, mu=3e-4).generate_paths()[:, 0]
    index = pd.bdate_range("2010-01-04", periods=path.size)
    return pd.Series(path, index=index)


def _mean_and_se(x: np.ndarray) -> tuple[float, float]:
    return float(np.mean(x)), float(np.std(x, ddof=1) / math.sqrt(x.size))


@pytest.fixture(scope="module")
def calibrated() -> GarchTSimulator:
    sim = GarchTSimulator.from_days(S0, 30, 500, 5)
    sim.calibrate(_synthetic_prices())
    return sim


