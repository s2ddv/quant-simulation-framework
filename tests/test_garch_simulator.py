def test_shape_dtype_row_zero_and_variance_matrix() -> None:
    paths = _sim(30, 400, 9).generate_paths()
    assert paths.shape == (31, 400) and paths.dtype == np.float64
    assert np.all(paths[0] == S0) and np.isfinite(paths).all() and np.all(paths > 0)
    h0 = 3 * S2
    p2, hvar = _sim(30, 400, 9, h0=h0).generate_paths_and_variance()
    assert p2.shape == hvar.shape == (31, 400) and hvar.dtype == np.float64
    assert np.all(hvar[0] == h0) and np.all(hvar > 0)
    # Same draws with and without the variance matrix (same seed).
    np.testing.assert_array_equal(_sim(30, 400, 9, h0=h0).generate_paths(), p2)
    # Variance recursion re-applied to the shocks recovered from prices.
    e = np.diff(np.log(p2), axis=0) - MU
    expected = PARAMS["omega"] + PARAMS["alpha"] * e * e + PARAMS["beta"] * hvar[:-1]
    np.testing.assert_allclose(hvar[1:], expected, rtol=1e-9)


def test_memory_budget_rejected_before_allocation() -> None:
    with pytest.raises(ValueError, match="bytes"):
        _sim(10000, 5000).generate_paths()          # 8*10001*5000 B ~ 400 MB
    # Paths alone (~144 MB) fit, paths + variance (~288 MB) do not.
    with pytest.raises(ValueError, match="bytes"):
        _sim(999, 18000).generate_paths_and_variance()


